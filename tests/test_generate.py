def generate(tree: Tree, host: str) -> Config:
    argv = (
        sys.executable,
        str(ROOT / 'luna.py'),
        '-z',
        str(tree.zone_file),
        '-i',
        str(tree.input_file),
        '-o',
        '-',
        host,
    )
    out = subprocess.run(
        argv,
        capture_output=True,
        text=True,
        check=True,
        timeout=30,
        env=os.environ | {'LUNA_MUTE': '1'},
    ).stdout
    return Config(StringIO(out))


def opts(cfg: Config, host: str) -> list[str]:
    return [str(line) for line in cfg.query(host)]


def test_remote_zone_is_reached_through_its_gateway(tree: Tree):
    assert 'ProxyJump ofgw' in opts(generate(tree, 'ofbox'), 'ofbox')


def test_local_zone_needs_no_jump(tree: Tree):
    assert 'proxyjump' not in {line.dir.opt for line in generate(tree, 'box1').query('box1')}


def test_direct_alias_inherits_the_connection_options(tree: Tree):
    # 'd.<host>' exists to bypass the jump chain, so it needs the whole set.
    assert opts(generate(tree, 'ofbox'), 'd.ofgw') == [
        'Hostname 192.168.1.1',
        'Port 2222',
    ]


needs_ssh = pytest.mark.skipif(shutil.which('ssh') is None, reason='needs ssh(1)')


def test_generator_requires_an_input_file(tree: Tree):
    argv = (sys.executable, str(ROOT / 'luna.py'), '-z', str(tree.zone_file), '-o', '-')
    r = subprocess.run(
        argv,
        check=False,
        capture_output=True,
        text=True,
        timeout=30,
        env=os.environ | {'LUNA_MUTE': '1'},
    )
    assert r.returncode == 2
    assert '-i/--input-file' in r.stderr


def generate_file(tree: Tree, tmp_path: Path, force: str = '-f') -> Path:
    out = tmp_path / 'config.inc'
    argv = (
        sys.executable,
        str(ROOT / 'luna.py'),
        '-z',
        str(tree.zone_file),
        '-i',
        str(tree.input_file),
        '-o',
        str(out),
        force,
        'ofbox',
    )
    subprocess.run(
        argv, check=True, capture_output=True, timeout=30, env=os.environ | {'LUNA_MUTE': '1'}
    )
    return out


def ssh_g(file: Path, host: str) -> list[str]:
    # ssh exits 255 and abandons the file when a keyword arrives with no argument.
    return subprocess.run(
        ('ssh', '-G', '-F', str(file), host),
        check=True,
        capture_output=True,
        text=True,
        timeout=30,
    ).stdout.splitlines()


# The names a client that lists hosts offers: the literal patterns of `Host` lines.
def listed(file: Path) -> list[str]:
    names: list[str] = []
    for line in file.read_text(encoding='utf-8').splitlines():
        keyword, *patterns = line.split('#', 1)[0].split() or ('',)
        if keyword.lower() == 'host':
            names.extend(p for p in patterns if not any(c in p for c in '*?!'))
    return names


